"""18. Property Decorators: @property, @setter, and @deleter
Assignment:
Create a class Product with a private attribute _price. Use @property to get the price, @price.setter to update it, and @price.deleter to delete it.
"""

class Product:
    def __init__(self, name, price):
        self.name = name
        self._price = price  # Private attribute

    # Getter: @property to access the price
    @property
    def price(self):
        print("Getting price...")
        return self._price

    # Setter: @price.setter to update the price
    @price.setter
    def price(self, new_price):
        if new_price < 0:
            raise ValueError("Price cannot be negative")
        print("Setting price...")
        self._price = new_price

    # Deleter: @price.deleter to delete the price
    @price.deleter
    def price(self):
        print("Deleting price...")
        del self._price


# Example usage:
product = Product("Laptop", 1000)

# Access the price (using the getter)
print(product.price)  # Output: Getting price... 1000

# Update the price (using the setter)
product.price = 1200  # Output: Setting price...
print(product.price)  # Output: Getting price... 1200

# Try deleting the price (using the deleter)
