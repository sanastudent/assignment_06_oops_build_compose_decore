"""21. Make a Custom Class Iterable
Assignment:
Create a class Countdown that takes a start number. Implement __iter__() and __next__() to make the object iterable in a for-loop, counting down to 0.
"""

class Countdown:
    def __init__(self, start):
        self.start = start  # Initialize with a start number

    def __iter__(self):
        self.current = self.start  # Set the current number to the start value
        return self  # Return the iterator object itself

    def __next__(self):
        if self.current <= 0:
            raise StopIteration  # Stop iteration when the countdown reaches 0
        else:
            self.current -= 1  # Decrement the counter
            return self.current  # Return the current countdown value


# Example usage:
countdown = Countdown(5)

# Using the countdown object in a for-loop
for number in countdown:
    print(number)